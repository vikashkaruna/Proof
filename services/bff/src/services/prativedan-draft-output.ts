/** Pure, unmounted verification. Witnesses must be independently loaded from
 * actual ledger rows; an authenticated envelope alone is never settlement proof.
 */
import { parseFragment, type DefaultTreeAdapterMap } from 'parse5';
import { canonicalJson } from '@axiom/ledger';
import {
  PRATIVEDAN_RENDERER_AGENT_VERSION,
  PRATIVEDAN_RENDERER_CONFIG_VERSION,
  PRATIVEDAN_RENDERER_CONFIG_TEXT,
  PRATIVEDAN_RENDERER_CONFIG_SHA256,
  prativedanRuntimeEnvelopeSchema,
  prativedanReceiptWitnessSchema,
  prativedanRendererInputSchema,
  prativedanDraftOutputSchema,
  type PrativedanDraftOutput,
} from '@axiom/types';
import {
  PrativedanDraftRefused,
  preparePrativedanDraftSource,
  prativedanTextHash,
  parsePrativedanJson,
  type PreparedPrativedanDraftSource,
} from './prativedan-draft-source.js';

type Node = DefaultTreeAdapterMap['node'];
const bindingFields = [
  'tenant_id',
  'engagement_id',
  'source_id',
  'assessment_run_id',
  'run_id',
  'operation_key',
  'source_sha256',
  'request_sha256',
  'runtime_normalized_input_sha256',
  'runtime_output_sha256',
  'renderer_config_version',
  'renderer_config_sha256',
  'agent',
  'agent_version',
  'correlation_id',
  'target_ref',
  'requested_receipt',
  'started_receipt',
  'completed_receipt',
] as const;
const allowedTags = new Set([
  'h1',
  'div',
  'p',
  'strong',
  'h2',
  'table',
  'thead',
  'tr',
  'th',
  'tbody',
  'td',
]);
function nodeText(node: Node): string {
  if (node.nodeName === '#text' && 'value' in node) return node.value;
  return 'childNodes' in node ? node.childNodes.map(nodeText).join('') : '';
}
function inspectHtml(node: Node): void {
  if ('tagName' in node) {
    if (
      !allowedTags.has(node.tagName) ||
      node.namespaceURI !== 'http://www.w3.org/1999/xhtml' ||
      node.attrs.some(
        (attribute) =>
          node.tagName !== 'div' || attribute.name !== 'class' || attribute.value !== 'axiom-cover',
      )
    )
      throw new PrativedanDraftRefused();
  } else if (node.nodeName !== '#text' && node.nodeName !== '#document-fragment')
    throw new PrativedanDraftRefused();
  if ('childNodes' in node) node.childNodes.forEach(inspectHtml);
}
function regexText(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
function pythonRoundedScore(value: number): number {
  const floor = Math.floor(value);
  return value - floor === 0.5 ? floor + (floor % 2) : Math.round(value);
}

function verifyProjection(
  prepared: PreparedPrativedanDraftSource,
  output: PrativedanDraftOutput,
  agentVersion: string,
): string {
  const input = prepared.rendererInput;
  if (output.title !== input.title || output.kind !== input.kind)
    throw new PrativedanDraftRefused();
  const [summary, findings, library, attribution] = output.sections;
  const expectedItems = input.findings
    .slice(0, 10)
    .map((finding) => ({ ...finding, risk_points: null }));
  if (
    canonicalJson(findings.items) !== canonicalJson(expectedItems) ||
    summary.title !== 'Executive summary' ||
    findings.title !== 'Findings for review (source order)' ||
    library.title !== 'Control library' ||
    attribution.title !== 'Draft attribution and review status' ||
    library.body !==
      `Referenced library version: ${input.library_version}. Draft input declares ${input.library_control_ids.length} controls; frozen source verification remains required.` ||
    attribution.body !==
      `Generated by Prativedan (v${agentVersion}). Pending recorded human review. Evidence references are unverified.`
  )
    throw new PrativedanDraftRefused();
  const score = input.posture_score;
  const verdict =
    score === null
      ? 'Unknown'
      : score >= 85
        ? 'Strong'
        : score >= 65
          ? 'Acceptable'
          : score >= 40
            ? 'At Risk'
            : 'Critical';
  const posture =
    score === null
      ? 'Posture score: Unknown (not supplied).'
      : `Declared posture score: ${pythonRoundedScore(score)}/100 (${verdict}; provisional).`;
  const tail = `${input.findings.length} findings included for review. Library version: ${input.library_version}.`;
  if (input.estimated_exposure_inr === null) {
    if (summary.body !== `${posture} Estimated statutory exposure: Unknown (not supplied). ${tail}`)
      throw new PrativedanDraftRefused();
  } else {
    // Validate displayed precision without pretending TS and Python float codecs match.
    const match = new RegExp(
      `^${regexText(posture)} Estimated statutory exposure \\(provisional\\): ₹([0-9]+\\.[0-9]{2}) Cr\\. ${regexText(tail)}$`,
    ).exec(summary.body);
    if (!match || Math.abs(Number(match[1]) * 1e7 - input.estimated_exposure_inr) > 50000 + 4)
      throw new PrativedanDraftRefused();
  }
  return score === null
    ? 'Unknown (not supplied)'
    : `${pythonRoundedScore(score)}/100 (${verdict}; provisional)`;
}

function verifyHtml(output: PrativedanDraftOutput, posture: string): void {
  const parsed = parseFragment(output.rendered_html);
  inspectHtml(parsed);
  const roots = parsed.childNodes.filter(
    (node) => node.nodeName !== '#text' || nodeText(node).trim(),
  );
  const tags = roots.map((node) => ('tagName' in node ? node.tagName : 'text'));
  if (
    canonicalJson(tags) !==
    canonicalJson(['h1', 'div', 'h2', 'p', 'h2', 'table', 'h2', 'p', 'h2', 'p'])
  )
    throw new PrativedanDraftRefused();
  const [summary, findings, library, attribution] = output.sections;
  const expected = [
    output.title,
    `Posture: ${posture}`,
    summary.title,
    summary.body,
    findings.title,
    null,
    library.title,
    library.body,
    attribution.title,
    attribution.body,
  ];
  roots.forEach((node, index) => {
    if (expected[index] !== null && nodeText(node) !== expected[index])
      throw new PrativedanDraftRefused();
  });
  const table = roots[5];
  if (!table || !('childNodes' in table)) throw new PrativedanDraftRefused();
  const rows: Node[] = [];
  const collect = (node: Node) => {
    if ('tagName' in node && node.tagName === 'tr') rows.push(node);
    if ('childNodes' in node) node.childNodes.forEach(collect);
  };
  collect(table);
  if (rows.length !== findings.items.length + 1) throw new PrativedanDraftRefused();
  rows.forEach((row, index) => {
    if (!('childNodes' in row)) throw new PrativedanDraftRefused();
    const cells = row.childNodes.filter((node) => 'tagName' in node);
    if (cells.length !== 5) throw new PrativedanDraftRefused();
    const values = cells.map(nodeText);
    if (index === 0) {
      if (
        canonicalJson(values) !==
        canonicalJson(['Control', 'Title', 'Severity', 'Score', 'Risk pts'])
      )
        throw new PrativedanDraftRefused();
    } else {
      const item = findings.items[index - 1]!;
      if (
        values[0] !== item.control_id ||
        values[1] !== item.title ||
        values[2] !== item.severity ||
        values[4] !== '' ||
        (item.score === null
          ? values[3] !== ''
          : !/^(?:[0-9]+(?:\.[0-9]+)?|[0-9]+(?:\.[0-9]+)?e[+-]?[0-9]+)$/i.test(values[3]!) ||
            Number(values[3]) !== item.score)
      )
        throw new PrativedanDraftRefused();
    }
  });
}

export function verifyPrativedanDraftOutput(
  prepared: PreparedPrativedanDraftSource,
  rawEnvelope: unknown,
  rawTrustedReceiptWitness: unknown,
) {
  try {
    // Recompose from retained bytes; mutable cached preparations cannot replace source truth.
    prepared = preparePrativedanDraftSource(prepared.witness, prepared.request);
    const envelope = prativedanRuntimeEnvelopeSchema.parse(rawEnvelope);
    const receipt = prativedanReceiptWitnessSchema.parse(rawTrustedReceiptWitness);
    for (const field of bindingFields)
      if (canonicalJson(envelope[field]) !== canonicalJson(receipt[field]))
        throw new PrativedanDraftRefused();
    // A matching self-declared manifest and receipt digest are insufficient:
    // pin the configuration actually reviewed for this renderer implementation.
    if (
      envelope.renderer_config_version !== PRATIVEDAN_RENDERER_CONFIG_VERSION ||
      envelope.renderer_config_text !== PRATIVEDAN_RENDERER_CONFIG_TEXT ||
      prativedanTextHash(envelope.renderer_config_text) !== PRATIVEDAN_RENDERER_CONFIG_SHA256 ||
      envelope.renderer_config_sha256 !== PRATIVEDAN_RENDERER_CONFIG_SHA256 ||
      envelope.agent_version !== PRATIVEDAN_RENDERER_AGENT_VERSION
    )
      throw new PrativedanDraftRefused();
    const source = prepared.witness;
    if (
      envelope.tenant_id !== source.tenant_id ||
      envelope.engagement_id !== source.engagement_id ||
      envelope.source_id !== source.source_id ||
      envelope.assessment_run_id !== source.assessment_run_id ||
      envelope.operation_key !== prepared.request.operationKey ||
      envelope.correlation_id !== envelope.operation_key ||
      envelope.target_ref !== source.engagement_id ||
      envelope.source_sha256 !== source.source_sha256 ||
      envelope.request_sha256 !== prepared.requestSha256 ||
      BigInt(envelope.requested_receipt.id) <= BigInt(source.receipts.finalized.id) ||
      prativedanTextHash(envelope.normalized_input_text) !==
        receipt.runtime_normalized_input_sha256 ||
      prativedanTextHash(envelope.runtime_output_text) !== receipt.runtime_output_sha256
    )
      throw new PrativedanDraftRefused();
    const normalized = prativedanRendererInputSchema.parse(
      parsePrativedanJson(envelope.normalized_input_text),
    );
    if (canonicalJson(normalized) !== canonicalJson(prepared.rendererInput))
      throw new PrativedanDraftRefused();
    const output = prativedanDraftOutputSchema.parse(
      parsePrativedanJson(envelope.runtime_output_text),
    );
    if (canonicalJson(output) !== canonicalJson(envelope.output))
      throw new PrativedanDraftRefused();
    const posture = verifyProjection(prepared, output, receipt.agent_version);
    verifyHtml(output, posture);
    const responseOutputText = canonicalJson(output);
    return {
      output,
      responseOutputText,
      responseOutputSha256: prativedanTextHash(responseOutputText),
      sourceSha256: source.source_sha256,
      requestSha256: prepared.requestSha256,
      runtimeNormalizedInputSha256: receipt.runtime_normalized_input_sha256,
      runtimeOutputSha256: receipt.runtime_output_sha256,
      rendererConfigVersion: envelope.renderer_config_version,
      rendererConfigSha256: envelope.renderer_config_sha256,
    };
  } catch {
    throw new PrativedanDraftRefused();
  }
}
