def run(args: list[str], *, stdin: str | None = None, check: bool = True, timeout: int = 120):
    return subprocess.run(  # nosec B603 - fixed argv; secrets only ever on stdin
        args,
        input=stdin,
        capture_output=True,
        text=True,
        check=check,
        timeout=timeout,
    )


def private_dir(path: Path) -> Path:
    path.mkdir(mode=0o700, parents=True, exist_ok=True)
    path.chmod(0o700)
    return path


def private_write(path: Path, value: str) -> None:
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as stream:
        stream.write(value)
    path.chmod(0o600)


def secret_file(path: Path) -> str:
    """Return the existing secret, or create one. Never printed."""
    if path.exists():
        return path.read_text().strip()
    value = secrets.token_urlsafe(32)
    private_write(path, value + "\n")
    return value


def ensure_ca() -> Path:
    ca_dir = private_dir(STATE / "ca")
    if not (ca_dir / "ca.pem").exists():
        run(["openssl", "ecparam", "-name", "prime256v1", "-genkey", "-noout",
             "-out", str(ca_dir / "ca.key")])
        run(["openssl", "req", "-x509", "-new", "-key", str(ca_dir / "ca.key"), "-sha256",
             "-days", "825", "-subj", "/CN=Axiom Proof local demo database CA",
             "-addext", "basicConstraints=critical,CA:TRUE",
             "-addext", "keyUsage=critical,keyCertSign,cRLSign",
             "-out", str(ca_dir / "ca.pem")])
        for name in ("ca.key", "ca.pem"):
            (ca_dir / name).chmod(0o600)
    return ca_dir


def ensure_certificate(target: Target, ca_dir: Path) -> Path:
    tls = private_dir(STATE / target.name / "tls")
    if (tls / "server.crt").exists():
        return tls
    run(["openssl", "ecparam", "-name", "prime256v1", "-genkey", "-noout",
         "-out", str(tls / "server.key")])
    run(["openssl", "req", "-new", "-key", str(tls / "server.key"),
         "-subj", f"/CN={target.name}", "-out", str(tls / "server.csr")])
    extensions = tls / "server.ext"
    private_write(
        extensions,
        f"subjectAltName=DNS:{target.name},DNS:localhost,IP:127.0.0.1\n"
        "extendedKeyUsage=serverAuth\nkeyUsage=critical,digitalSignature\n",
    )
    run(["openssl", "x509", "-req", "-in", str(tls / "server.csr"),
         "-CA", str(ca_dir / "ca.pem"), "-CAkey", str(ca_dir / "ca.key"),
         "-CAcreateserial", "-days", "397", "-sha256", "-extfile", str(extensions),
         "-out", str(tls / "server.crt")])
    run(["cp", str(ca_dir / "ca.pem"), str(tls / "ca.pem")])
    for item in tls.iterdir():
        item.chmod(0o600)
    return tls


def container_state(name: str) -> dict | None:
    result = run(["docker", "inspect", name], check=False)
    if result.returncode:
        return None
    info = json.loads(result.stdout)[0]
    if info["Config"]["Labels"].get("axiom.purpose") != PURPOSE:
        raise SystemExit(f"{name} exists but is not an owned demo database; refusing to touch it")
    return info


def server_command(target: Target) -> list[str]:
    """Copy the TLS material to the engine user (bind mounts keep host
    ownership) and start the official entrypoint with TLS required."""
    if target.engine == "postgresql":
        prepare = (
            "install -d -o postgres -g postgres -m 700 /var/lib/postgresql/tls && "
            "install -o postgres -g postgres -m 600 /tls-src/server.key /tls-src/server.crt "
            "/var/lib/postgresql/tls/ && "
            "printf 'local all all trust\\nhostssl all all all scram-sha-256\\n' "
            "> /var/lib/postgresql/tls/pg_hba.conf && chown postgres /var/lib/postgresql/tls/pg_hba.conf && "
            "exec docker-entrypoint.sh postgres -c ssl=on "
            "-c ssl_cert_file=/var/lib/postgresql/tls/server.crt "
            "-c ssl_key_file=/var/lib/postgresql/tls/server.key "
            "-c ssl_min_protocol_version=TLSv1.2 "
            "-c hba_file=/var/lib/postgresql/tls/pg_hba.conf"
        )
    else:
        user = "mysql"
        prepare = (
            f"install -d -o {user} -g {user} -m 700 /etc/axiom-tls && "
            f"install -o {user} -g {user} -m 600 /tls-src/server.key /tls-src/server.crt "
            "/tls-src/ca.pem /etc/axiom-tls/ && "
            "exec docker-entrypoint.sh --ssl-cert=/etc/axiom-tls/server.crt "
            "--ssl-key=/etc/axiom-tls/server.key --ssl-ca=/etc/axiom-tls/ca.pem "
            "--require-secure-transport=ON --tls-version=TLSv1.2,TLSv1.3"
        )
    return ["sh", "-c", prepare]


def start(target: Target, tls: Path) -> None:
    root_secret = STATE / target.name / "root.password"
    secret_file(root_secret)
    env = {
        "postgresql": ["-e", "POSTGRES_PASSWORD_FILE=/run/axiom/root.password",
                       "-e", f"POSTGRES_DB={target.database}"],
        "mysql": ["-e", "MYSQL_ROOT_PASSWORD_FILE=/run/axiom/root.password"],
        "mariadb": ["-e", "MARIADB_ROOT_PASSWORD_FILE=/run/axiom/root.password"],
    }[target.engine]
    data = {"postgresql": "/var/lib/postgresql/data", "mysql": "/var/lib/mysql",
            "mariadb": "/var/lib/mysql"}[target.engine]
    run([
        "docker", "run", "-d", "--name", target.name, "--hostname", target.name,
        "--label", f"axiom.purpose={PURPOSE}", "--label", "ai.axiom.environment=local",
        "--label", f"axiom.demo.company={target.company}",
        "--network", NETWORK, "--network-alias", target.name,
        "-p", f"127.0.0.1:{target.port}:{5432 if target.engine == 'postgresql' else 3306}",
        "--restart", "unless-stopped",
        "--mount", f"type=volume,src={target.name}-data,dst={data}",
        "--mount", f"type=bind,src={tls},dst=/tls-src,readonly",
        "--mount", f"type=bind,src={root_secret},dst=/run/axiom/root.password,readonly",
        "--mount", f"type=bind,src={ROOT / 'infra/demo-targets' / target.seed / 'seed.sql'},"
                   "dst=/docker-entrypoint-initdb.d/10-seed.sql,readonly",
        *env, "--entrypoint", "", target.image, *server_command(target),
    ])


def admin_sql(target: Target, sql: str) -> str:
    """Run administrative SQL inside the container. Secrets travel on stdin."""
    if target.engine == "postgresql":
        args = ["docker", "exec", "-i", target.name, "psql", "-X", "-q", "-v", "ON_ERROR_STOP=1",
                "-U", "postgres", "-d", target.database, "-At"]
        return run(args, stdin=sql).stdout
    client = "mysql" if target.engine == "mysql" else "mariadb"
    root = (STATE / target.name / "root.password").read_text().strip()
    # The root password is a protected local file; it reaches the client via
    # the exec environment (not the container config) and never via argv.
    args = ["docker", "exec", "-i", "-e", f"MYSQL_PWD={root}", target.name, client,
            *(["--ssl"] if target.engine == "mariadb" else []),
            "-uroot", "-h", "127.0.0.1", "--protocol=tcp", "-N", "-B"]
    return run(args, stdin=sql).stdout


def ready(target: Target) -> bool:
    probe = {
        "postgresql": "select count(*) from core.service_notes",
        "mysql": "select count(*) from his.appointment_notes",
        "mariadb": "select count(*) from app.audit_logs",
    }[target.engine]
    try:
        return admin_sql(target, probe + ";").strip() not in ("", "0")
    except subprocess.CalledProcessError:
        return False


def quote(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "''") + "'"


def set_accounts(target: Target) -> None:
    reader = secret_file(STATE / target.name / f"{READER}.password")
    over = secret_file(STATE / target.name / f"{OVERPRIVILEGED}.password")
    if target.engine == "postgresql":
        admin_sql(target, f"alter role {READER} password {quote(reader)};\n"
                          f"alter role {OVERPRIVILEGED} password {quote(over)};\n")
        return
    db = target.database
    statements = [
        f"create user if not exists '{READER}'@'%' identified by {quote(reader)} require ssl;",
        f"alter user '{READER}'@'%' identified by {quote(reader)} require ssl;",
        f"grant select on {db}.* to '{READER}'@'%';",
        f"create user if not exists '{OVERPRIVILEGED}'@'%' identified by {quote(over)} require ssl;",
        f"alter user '{OVERPRIVILEGED}'@'%' identified by {quote(over)} require ssl;",
        f"grant select, insert on {db}.* to '{OVERPRIVILEGED}'@'%';",
        "flush privileges;",
    ]
    admin_sql(target, "\n".join(statements) + "\n")


def up(_args) -> None:
    if run(["docker", "network", "inspect", NETWORK], check=False).returncode:
        raise SystemExit(f"Local app network {NETWORK} is missing; start the local stack first")
    private_dir(STATE)
    ca_dir = ensure_ca()
    for target in TARGETS:
        tls = ensure_certificate(target, ca_dir)
        if container_state(target.name) is None:
            start(target, tls)
            print(f"{target.name}: started")
    for target in TARGETS:
        for _ in range(120):
            if ready(target):
                break
            time.sleep(2)
        else:
            raise SystemExit(f"{target.name}: not ready; inspect `docker logs {target.name}`")
        set_accounts(target)
        print(f"{target.name}: ready ({target.engine}, 127.0.0.1:{target.port}, TLS required)")


def status(_args) -> None:
    for target in TARGETS:
        info = container_state(target.name)
        state = info["State"]["Status"] if info else "absent"
        print(f"{target.name:30} {target.engine:10} {state:10} 127.0.0.1:{target.port}  {target.company}")


def down(args) -> None:
    for target in TARGETS:
        if container_state(target.name) is not None:
            run(["docker", "rm", "-f", target.name])
            print(f"{target.name}: removed")
        if args.purge:
            run(["docker", "volume", "rm", f"{target.name}-data"], check=False)
            for item in sorted((STATE / target.name).rglob("*"), reverse=True):
                item.rmdir() if item.is_dir() else item.unlink()
            if (STATE / target.name).exists():
                (STATE / target.name).rmdir()
    if args.purge:
        print("Data volumes and protected files removed; the local CA is kept.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("up").set_defaults(func=up)
    commands.add_parser("status").set_defaults(func=status)
    commands.add_parser("down").set_defaults(func=down, purge=False)
    commands.add_parser("purge").set_defaults(func=down, purge=True)
    args = parser.parse_args()
    try:
        args.func(args)
    except subprocess.CalledProcessError as error:
        # Never echo stdin (it may carry a password); stderr is the engine's own message.
        sys.exit(f"Command failed ({error.cmd[0]} {error.cmd[1]}): {error.stderr.strip()[:400]}")


if __name__ == "__main__":
    main()
